def create_node_executor(node_id: str, session_manager: KimiSessionManager):
    """Create a node executor function for LangGraph pipeline.

    This factory function returns an async node function that:
    1. Loads node configuration via NodeLoader
    2. Creates a DualAgentNode instance
    3. Executes the node with pipeline state
    4. Updates state with deliverable, questions, evaluations
    5. Tracks iteration count
    6. Adds node to completed_nodes on APPROVED verdict

    Args:
        node_id: The node identifier (e.g., 'analyst', 'pm', 'ux', 'architect', 'po')
        session_manager: KimiSessionManager for SDK interactions.

    Returns:
        An async function that accepts PipelineState and returns updated PipelineState
    """
    # Create logger with node_id bound
    logger = structlog.get_logger().bind(node_id=node_id)

    async def node_executor(state: PipelineState) -> PipelineState:
        """Async node executor function for LangGraph.

        Args:
            state: The current pipeline state

        Returns:
            Updated pipeline state with node results
        """
        return await _execute_node(state, node_id, session_manager, logger)

    return node_executor


async def _execute_node(
    state: PipelineState,
    node_id: str,
    session_manager: KimiSessionManager,
    logger: StructlogBoundLogger,
) -> PipelineState:
    """Execute a node and update pipeline state.

    Args:
        state: The current pipeline state
        node_id: The node identifier to execute
        session_manager: KimiSessionManager for SDK interactions.
        logger: Bound structlog logger

    Returns:
        Updated pipeline state
    """
    import copy

    from autoBMAD.docuswarm.nodes.loader import NodeLoader

    logger.info("node_execution_started", node_id=node_id)

    # Create a deep copy of state to avoid mutation of nested dicts/lists
    new_state = copy.deepcopy(state)

    # Update current_node
    new_state["current_node"] = node_id

    # Load node configuration (currently not used but kept for future validation)
    loader = NodeLoader()
    _ = loader.load(node_id)

    # Create DualAgentNode instance
    # Get config from global or create default (for now, use placeholder)
    # In production, this would come from dependency injection
    config = _get_config()

    node = create_dual_agent_node(
        config=config,
        session_manager=session_manager,
        node_id=node_id,
    )

    # Execute the node
    subject_context = state.get("subject_context", {})
    task = subject_context.get("task", "")
    # Get pipeline_id from state for IndependentAgent (Story 11.1)
    pipeline_id = state.get("pipeline_id", "")

    try:
        result = await node.execute(
            subject_context=str(subject_context),
            task=task,
            pipeline_id=pipeline_id,
        )

        # Update deliverables
        new_state["deliverables"][node_id] = result.deliverable

        # Update questions
        new_state["questions"][node_id] = result.questions

        # Update evaluations
        new_state["evaluations"][node_id] = result.evaluation

        # Update iteration count
        current_iterations = new_state["node_iterations"].get(node_id, 0)
        new_state["node_iterations"][node_id] = current_iterations + result.iteration

        # Check verdict and update completed_nodes
        verdict = result.evaluation.get("verdict") if result.evaluation else None
        if verdict == "APPROVED" or verdict == "FORCE_APPROVED":
            if node_id not in new_state["completed_nodes"]:
                new_state["completed_nodes"].append(node_id)
            logger.info(
                "node_approved", node_id=node_id, iteration=result.iteration, verdict=verdict
            )
        else:
            logger.info(
                "node_not_approved",
                node_id=node_id,
                verdict=verdict,
                iteration=result.iteration,
            )

        logger.info(
            "node_execution_completed",
            node_id=node_id,
            iteration=result.iteration,
            verdict=verdict,
        )

    except Exception as e:
        logger.error("node_execution_failed", node_id=node_id, error=str(e))
        raise

    return new_state


