"""Dual-Agent Node Implementation - Story 2.9.

This module provides the DualAgentNode class which:
- Coordinates Independent and Evaluator agents
- Filters private_reasoning from Independent Agent output before passing to Evaluator
- Supports iteration loop when Evaluator returns NEEDS_REVISION verdict
- Passes previous feedback to Independent Agent on retry iterations
- Tracks and reports iteration count in final result
- Handles edge cases where Independent Agent returns malformed output
- Ensures Evaluator never receives private_reasoning field
"""

